from contextlib import AbstractContextManager
from pathlib import Path
from typing import Protocol


class PipelineGate(Protocol):
    """One job at a time, in pipeline order, one forecast run at a time. Raises PipelineBlockedError otherwise."""

    # carry_over: the current parameters of each import ({task: params}), sent with an import launch: the launched
    # event keeps the import's own, and a launch that starts a pass carries over the imports already done in the cycle
    # with the same parameters and DRYRUN (cycle-passes.md § 11).
    def start(self, task: str, job_id: str, confirm: bool = False, carry_over: dict[str, dict] | None = None) -> None: ...

    def finish(self, job_id: str, status: str) -> None: ...

    def run(self, task: str, job_id: str, confirm: bool = False) -> AbstractContextManager[None]: ...

    def change_input(self, name: str, confirm: bool = False, removed: bool = False) -> AbstractContextManager[None]: ...

    def launch_cycle(self) -> str: ...

    def set_cycle(self, cycle: str | None) -> dict: ...

    def open_run(self, couple: str, confirm: bool = False) -> dict: ...

    def abandon_run(self) -> str: ...

    def decide(self, decision: str) -> str: ...

    def skip_alerts(self) -> str: ...

    def decide_imports(self, decision: str) -> None: ...

    def reusable_availability(self, params: dict[str, str]) -> dict[str, dict]: ...

    # started_at: local ISO time with microseconds, the format of the journal's `at` (compared with launches).
    def record_availability_check(self, event: str, detail: dict, sections: list[dict] = (),
                                  started_at: str | None = None) -> dict: ...

    def progress(self, pass_id: str | None = None) -> dict: ...

    def release_lock(self) -> str | None: ...

    def set_mode(self, test_mode: bool) -> dict: ...

    def report(self, pass_id: str | None, couple: str) -> Path | None: ...

    def pause(self) -> dict: ...

    def resume(self, pass_id: str) -> dict: ...

    def abandon(self, pass_id: str) -> dict: ...

    def journal(self, pass_id: str) -> list[dict]: ...

    def cycles(self) -> list[dict]: ...
