from contextlib import AbstractContextManager
from pathlib import Path
from typing import Protocol, runtime_checkable


@runtime_checkable
class PipelineGate(Protocol):
    """One job at a time, in pipeline order, one forecast run at a time. Raises PipelineBlockedError otherwise."""

    def start(self, task: str, job_id: str, confirm: bool = False) -> None: ...

    def finish(self, job_id: str, status: str) -> None: ...

    def run(self, task: str, job_id: str, confirm: bool = False) -> AbstractContextManager[None]: ...

    def change_input(self, name: str, confirm: bool = False, removed: bool = False) -> AbstractContextManager[None]: ...

    def launch_cycle(self) -> str: ...

    def set_cycle(self, cycle: str | None) -> dict: ...

    def open_run(self, couple: str, confirm: bool = False) -> dict: ...

    def abandon_run(self) -> str: ...

    def decide(self, decision: str) -> str: ...

    def skip_alerts(self) -> str: ...

    def decide_imports(self, decision: str) -> None: ...

    def progress(self, cycle: str | None = None) -> dict: ...

    def release_lock(self) -> str | None: ...

    def set_mode(self, dry_run: bool, confirm: bool = False) -> dict: ...

    def report(self, cycle: str | None, couple: str) -> Path | None: ...

    def journal(self, cycle: str) -> list[dict]: ...

    def cycles(self) -> list[dict]: ...
