from typing import Protocol


class AuthStore(Protocol):
    """The active DHIS2 credential, the sessions and the failed-login counters."""

    def get_credential(self) -> dict | None: ...

    def set_credential(self, credential: dict, ttl: int) -> None: ...

    def delete_credential(self) -> None: ...

    def create_session(self, user: dict, pat_uid: str, ttl: int) -> str: ...

    def get_session(self, session_id: str) -> dict | None: ...

    def delete_session(self, session_id: str) -> None: ...

    def failed_logins(self, ip: str, username: str) -> int: ...

    def record_failed_login(self, ip: str, username: str, window: int) -> None: ...

    def clear_failed_logins(self, ip: str, username: str) -> None: ...
